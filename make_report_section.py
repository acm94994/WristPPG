"""Writes report/extension_section.tex from the result files. Only the method settings are typed here.

  python make_report_section.py

Reads results/collision, results/collision_oracle (run_collision.py --gate-hr ecg) and results/option3.
Intervals: subject-level bootstrap, 8 subjects, 5000 resamples, fixed seed.
"""
import os
import numpy as np
import pandas as pd

OUT = "report/extension_section.tex"
METHODS = [("mu", r"$\mu$ cut"), ("hold", "Hold weights"), ("aware-only", "Tracker change only"),
           ("mu+aware", r"$\mu$ cut + tracker"), ("hold+aware", "Hold + tracker")]
ACTS = [("walk", "Walk"), ("run", "Run"), ("low_resistance_bike", "Bike, low"), ("high_resistance_bike", "Bike, high")]


def boot(v, n=5000):
    v = np.asarray(v, float)
    m = np.random.default_rng(0).integers(0, len(v), (n, len(v)))
    return v.mean(), *np.percentile(v[m].mean(1), [2.5, 97.5])


def change(sc, m, metric="mae"):
    """Per-subject mean change vs ANC."""
    b = sc[sc.method == "ANC"].set_index("record")[metric]
    q = sc[sc.method == m].copy()
    q["d"] = q[metric] - q.record.map(b)
    return q.groupby("subject").d.mean(), q.set_index("record").d


def ci(x, f="{:+.1f}"):
    m, lo, hi = boot(x)
    return f"{f.format(m)} [{f.format(lo)}, {f.format(hi)}]".replace("-", "$-$")


def main():
    cen = pd.read_csv("results/collision/census.csv")
    sc = pd.read_csv("results/collision/scores.csv")
    se = pd.read_csv("results/collision_oracle/scores.csv")
    ht = pd.read_csv("results/collision/holdtest.csv")
    inj = pd.read_csv("results/option3/injected.csv")
    anc = sc[sc.method == "ANC"].set_index("record").mae
    cen["mae"] = cen.record.map(anc)
    rho = cen[["frac_within_6", "mae"]].corr("spearman").iloc[0, 1]

    rows = []
    for a, name in ACTS:
        q = cen[cen.activity == a]
        rows.append(f"{name} & {len(q)} & {100 * q.frac_within_6.mean():.0f} & {100 * q.frac_within_15.mean():.0f} & "
                    f"{q.max_dur_s.max():.0f} & {q.mae.mean():.1f} \\\\")
    rows.append(r"\midrule")
    rows.append(f"All & {len(cen)} & {100 * cen.frac_within_6.mean():.0f} & {100 * cen.frac_within_15.mean():.0f} & "
                f"{cen.max_dur_s.max():.0f} & {cen.mae.mean():.1f} \\\\")
    census_rows = "\n".join(rows)

    gate_rows = [f"Gate active, share of time & {100 * sc[sc.method == 'hold'].hold_frac.mean():.0f}\\% & "
                 f"{100 * se[se.method == 'hold'].hold_frac.mean():.0f}\\% \\\\", r"\midrule"]
    for m, name in METHODS:
        gate_rows.append(f"{name} & {ci(change(sc, m)[0])} & {ci(change(se, m)[0])} \\\\")
    gate_rows = "\n".join(gate_rows)

    s4 = cen.set_index("record").loc["s4_run"]
    s4_hold = se[(se.method == "hold") & (se.record == "s4_run")].mae.iloc[0]
    hold_tr, rec_hold_tr = change(sc, "hold+aware")
    top = rec_hold_tr.idxmin()
    top_tex = top.replace("_", r"\_")
    top_new = sc[(sc.method == "hold+aware") & (sc.record == top)].mae.iloc[0]
    better = int((hold_tr < 0).sum())
    eps = ht.groupby("hold_s").epsilon.median()
    noto = sc[(sc.method.isin(["ANC", "hold+aware"])) & (sc.record != top)].groupby("method").mae.mean()

    inj = inj.assign(subject=inj.record.str.split("_").str[0])
    b = inj[inj.method == "ANC"].set_index("record")
    w = inj[inj.method == "WQN-both"].copy()
    w["p"] = (w.rmse_injected / w.record.map(b.rmse_injected) - 1) * 100
    wqn = ci(w.groupby("subject").p.mean())
    else_anc, else_wqn = b.rmse_elsewhere.mean(), w.rmse_elsewhere.mean()

    tex = rf"""% Generated by make_report_section.py from the result files. Do not edit by hand.
\subsection{{Extension: collision-aware adaptation}}
\label{{sec:collision}}
When the heart rate comes close to a motion harmonic, NLMS acts as a notch about $4.77\,\mu f_s$~BPM
wide (half-width) around that harmonic, so it removes pulse along with motion. We tested whether
gating the adaptation on the gap between HR and the cancelled motion lines avoids this. Cancelled
lines are read from the output $y=d-e$ of a slow pilot NLMS ($\mu=0.01$). The gate opens when the
tracked HR is within 12~BPM of a line. Inside the gate, either $\mu$ is cut by a factor of 10, or the
weights are held at their 4~s average, and optionally the tracker stops down-weighting motion bins.
The method takes two passes, so it is offline. Gate settings were locked in simulation before any real
data were scored, and each subject used its held-out NLMS-all settings. ECG is used only for scoring,
except in the upper bound below. The idea of freezing adaptation while the wanted signal is present is
established in echo cancellation [echo].

Table~\ref{{tab:census}} shows that collisions are common. Time within 6~BPM of a cancelled line does
not predict NLMS-all error across records, however (Spearman $\rho={rho:.2f}$).

\begin{{table}}[h]
\centering
\caption{{Time near a cancelled motion line, using true HR from ECG.}}
\label{{tab:census}}
\begin{{tabular}}{{lrrrrr}}
\toprule
Activity & Records & \% $<$6 BPM & \% $<$15 BPM & Longest (s) & NLMS-all MAE \\
\midrule
{census_rows}
\bottomrule
\end{{tabular}}
\end{{table}}

Table~\ref{{tab:gate}} gives the change in whole-record HR MAE against NLMS-all. With the tracked HR,
no method improved MAE with an interval excluding zero. The gate never fired on s4\_run, although that
record spends {100 * s4.frac_within_15:.0f}\% of its time within 15~BPM of a line, because the tracked
HR there averaged {s4.tracked_hr_zone:.0f}~BPM against a true {s4.true_hr_zone:.0f}~BPM. To check that
the negative result is not caused by the gate, the right-hand column gives the gate the true HR. This
is an upper bound, not a usable method. It still did not improve on NLMS-all: held weights took s4\_run
from {anc['s4_run']:.1f} to {s4_hold:.1f}~BPM. Hold + tracker with the tracked HR improved {better} of
{len(hold_tr)} subjects, but its mean gain comes from one record ({top_tex},
{anc[top]:.1f} to {top_new:.1f}~BPM). Without that record, NLMS-all scores {noto['ANC']:.2f} and
hold + tracker {noto['hold+aware']:.2f}~BPM. Held weights go stale quickly on real data: the leftover
motion amplitude relative to the input is already {eps.iloc[0]:.2f} after a {eps.index[0]}~s hold, so
the slowly drifting coupling the method assumes is not present.

\begin{{table}}[h]
\centering
\caption{{Change in whole-record HR MAE (BPM) against NLMS-all, mean over 8 subjects [95\% bootstrap CI].
Negative is better.}}
\label{{tab:gate}}
\begin{{tabular}}{{lcc}}
\toprule
Method & Gate on tracked HR & Gate on ECG HR (upper bound) \\
\midrule
{gate_rows}
\bottomrule
\end{{tabular}}
\end{{table}}

We therefore report the census as a finding and do not add gating to the main method. A second
extension, wavelet quantile normalisation [WQN] of the NLMS residual, gated by IMU jerks and the residual,
changed the error on injected transients by {wqn}\% (the target was $-$25\%) and raised error elsewhere from
{else_anc:.3f} to {else_wqn:.3f}, so it also failed its pre-set rule.
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(tex)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
